"""
One entry point, run from the repo root:

  python -m tact.run gen        write data/train.jsonl and data/test.jsonl
  python -m tact.run baseline   keyword router -> results/keyword.jsonl
  python -m tact.run predict --system NAME --base-url URL --model ID [--key-env VAR]
                                 any OpenAI-compatible endpoint -> results/NAME.jsonl
                                 (resumable: finished ids are skipped)
  python -m tact.run report     score every results/*.jsonl -> RESULTS.md

Console output is ASCII only.
"""
from __future__ import annotations

import argparse
import json
import os
import sys

from . import baseline, gen, prompt, score

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
RESULTS = os.path.join(ROOT, "results")
REPORT = os.path.join(ROOT, "RESULTS.md")
PRIMARY = "tact-ft"  # the fine-tuned model; every other system is compared to it


def test_rows() -> list[dict]:
    return gen.load(os.path.join(DATA, "test.jsonl"))


def load_preds(path: str) -> dict[str, str]:
    out = {}
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            for line in f:
                if line.strip():
                    r = json.loads(line)
                    out[r["id"]] = r["output"]
    return out


def save_preds(path: str, preds: dict[str, str]) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        for k in sorted(preds):
            f.write(json.dumps({"id": k, "output": preds[k]}, ensure_ascii=True) + "\n")


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def ci(pair) -> str:
    return f"[{100 * pair[0]:.1f}, {100 * pair[1]:.1f}]"


def render_report(rows: list[dict], systems: dict[str, dict]) -> str:
    order = sorted(systems, key=lambda s: (systems[s]["unsafe"], -systems[s]["exact"], s))
    n_tpl = len({r["template"] for r in rows})
    out = ["# Results", "",
           "Generated by `python -m tact.run report` -- do not edit by hand.", "",
           f"Test set: {len(rows)} requests from {n_tpl} held-out templates. "
           "Intervals are 95% cluster-bootstrap over templates.", "",
           "**Unsafe** = called a tool that changes something, and the call was "
           "not exactly right. Lower is better. It is the headline number.", "",
           "| System | Answered | Unsafe | 95% CI | Exact | 95% CI | Right tool "
           "| Abstains when it should | Unparseable |",
           "|---|---|---|---|---|---|---|---|---|"]
    for s in order:
        m = systems[s]
        out.append(f"| {s} | {m['answered']}/{m['n']} | {pct(m['unsafe'])} | "
                   f"{ci(m['unsafe_ci'])} | {pct(m['exact'])} | {ci(m['exact_ci'])} | "
                   f"{pct(m['tool_acc'])} | {pct(m['abstain_when_right'])} | "
                   f"{pct(m['parse_fail'])} |")
    out += ["", "## Exact match by category", "",
            "| System | " + " | ".join(f"{c} (n={sum(r['category'] == c for r in rows)})"
                                       for c in score.CATEGORIES) + " |",
            "|---|" + "---|" * len(score.CATEGORIES)]
    for s in order:
        bc = systems[s]["by_category"]
        out.append(f"| {s} | " + " | ".join(pct(bc[c]["exact"]) if c in bc else "-"
                                            for c in score.CATEGORIES) + " |")
    if PRIMARY in systems and len(systems) > 1:
        out += ["", f"## Paired test against {PRIMARY} (exact match, exact McNemar)", "",
                f"| Other system | {PRIMARY} right, other wrong | other right, "
                f"{PRIMARY} wrong | p |", "|---|---|---|---|"]
        for s in order:
            if s != PRIMARY:
                t = score.compare(systems[PRIMARY], systems[s])
                out.append(f"| {s} | {t['b']} | {t['c']} | {t['p']:.2g} |")
    out += ["", "## Why each system missed", ""]
    for s in order:
        why: dict[str, int] = {}
        for v in systems[s]["verdicts"]:
            if not v["exact"]:
                why[v["why"]] = why.get(v["why"], 0) + 1
        top = sorted(why.items(), key=lambda kv: (-kv[1], kv[0]))[:6]
        out.append(f"- **{s}**: " + (", ".join(f"{k} {n}" for k, n in top) or "no misses"))
    return "\n".join(out) + "\n"


def cmd_gen(_):
    counts = gen.write(DATA)
    print(f"train {counts['train']}  test {counts['test']}  -> {DATA}")


def cmd_baseline(_):
    path = os.path.join(RESULTS, "keyword.jsonl")
    save_preds(path, baseline.predict(test_rows()))
    print(f"keyword router -> {path}")


def cmd_predict(a):
    from .client import chat
    key = os.environ.get(a.key_env, "") if a.key_env else ""
    if a.key_env and not key:
        sys.exit(f"{a.key_env} is not set")
    path = os.path.join(RESULTS, f"{a.system}.jsonl")
    preds = load_preds(path)
    todo = [r for r in test_rows() if r["id"] not in preds][: a.limit or None]
    print(f"{a.system}: {len(preds)} done, {len(todo)} to go")
    try:
        for i, r in enumerate(todo, 1):
            preds[r["id"]] = chat(a.base_url, a.model, prompt.messages(r), key)
            if i % 20 == 0 or i == len(todo):
                save_preds(path, preds)
                print(f"  {i}/{len(todo)}")
    finally:
        save_preds(path, preds)


def cmd_report(_):
    rows = test_rows()
    systems = {}
    if os.path.isdir(RESULTS):
        for name in sorted(os.listdir(RESULTS)):
            if name.endswith(".jsonl"):
                systems[name[:-6]] = score.evaluate(
                    rows, load_preds(os.path.join(RESULTS, name)))
    text = render_report(rows, systems)
    with open(REPORT, "w", encoding="ascii", newline="\n") as f:
        f.write(text)
    for s, m in sorted(systems.items()):
        print(f"{s:24s} unsafe {pct(m['unsafe']):>6s}  exact {pct(m['exact']):>6s}  "
              f"answered {m['answered']}/{m['n']}")
    print(f"-> {REPORT}")


def main(argv=None):
    ap = argparse.ArgumentParser(prog="tact")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("gen").set_defaults(fn=cmd_gen)
    sub.add_parser("baseline").set_defaults(fn=cmd_baseline)
    sub.add_parser("report").set_defaults(fn=cmd_report)
    p = sub.add_parser("predict")
    p.add_argument("--system", required=True)
    p.add_argument("--base-url", required=True)
    p.add_argument("--model", required=True)
    p.add_argument("--key-env", default="")
    p.add_argument("--limit", type=int, default=0)
    p.set_defaults(fn=cmd_predict)
    a = ap.parse_args(argv)
    a.fn(a)


if __name__ == "__main__":
    main()
